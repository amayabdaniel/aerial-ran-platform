#!/usr/bin/env bash
# Generate infra/k8s/platform/secrets.env with FRESH random credentials for the
# aerial-secrets Secret (consumed by the kustomize secretGenerator in that dir).
#
# The real secrets.env is gitignored, so credentials never enter version control.
# Idempotent: if the file already exists it is left untouched, so repeated
# `make k8s-up` runs keep the same password the running Postgres was initialised
# with. Delete the file to rotate.
set -euo pipefail

dir="$(cd "$(dirname "$0")/../infra/k8s/platform" && pwd)"
out="$dir/secrets.env"

if [ -f "$out" ]; then
  echo "secrets.env already present at $out — leaving it untouched (delete it to rotate)"
  exit 0
fi

# base64 random, stripped of non-alphanumerics, trimmed to a fixed length.
rand() { openssl rand -base64 "$1" | tr -dc 'A-Za-z0-9' | cut -c1-"$2"; }
jwt="$(rand 48 48)"   # HS256 signing key, well over the 32-byte minimum
pass="$(rand 32 24)"  # Postgres password

user="aerial_admin"
host="postgres.aerial.svc.cluster.local:5432"
dbname="aerial"
dsn() { printf 'postgres://%s:%s@%s/%s?sslmode=disable&search_path=%s' "$user" "$pass" "$host" "$dbname" "$1"; }

umask 077
{
  echo "# GENERATED by scripts/gen-secrets.sh — gitignored, do NOT commit."
  echo "POSTGRES_PASSWORD=$pass"
  echo "JWT_SECRET=$jwt"
  for schema in iam subscriber esim provision ranctl billing messaging; do
    key="DATABASE_URL_$(printf '%s' "$schema" | tr '[:lower:]' '[:upper:]')"
    echo "$key=$(dsn "$schema")"
  done
} > "$out"

echo "wrote $out (fresh credentials, mode 600)"
